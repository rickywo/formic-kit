class TestClaudeTemplates(unittest.TestCase):
    def frontmatter(self, text):
        parts = text.split("\n---\n", 1)
        self.assertEqual(parts[0].splitlines()[0], "---")
        return parts[0].splitlines()[1:], parts[1]

    def test_templates_have_no_model_id(self):
        for name in AGENTS:
            text = (ROOT / "agents" / (name + ".claude.md.tmpl")).read_text()
            front, body = self.frontmatter(text)
            self.assertEqual(front[0], "name: " + name)
            for line in text.splitlines():
                self.assertFalse(re.match(r"\s*(model|mode|permission|permissionMode|tools)\s*:", line), line)
            self.assertIsNone(re.search(r"anthropic|bedrock|claude-(haiku|sonnet|opus)", text, re.I))
            self.assertTrue(body.startswith("<!--"))
            self.assertIn("<!-- " + MARKER + "; rerun install.sh to update, do not edit by hand -->",
                          body.splitlines()[0])
            self.assertNotIn("{{MODEL}}", text)

    def test_description_matches_opencode_template(self):
        for name in AGENTS:
            new = (ROOT / "agents" / (name + ".claude.md.tmpl")).read_text()
            old = (ROOT / "agents" / (name + ".md.tmpl")).read_text()
            pick = lambda t: [ln for ln in t.splitlines() if ln.startswith("description: ")][0]
            self.assertEqual(pick(new), pick(old))
            self.assertNotRegex(pick(new)[len("description: "):], r": | #")

    def test_body_matches_opencode_template(self):
        for name in AGENTS:
            new = (ROOT / "agents" / (name + ".claude.md.tmpl")).read_text()
            old = (ROOT / "agents" / (name + ".md.tmpl")).read_text()
            new_body = new.split("\n---\n", 1)[1].split("\n", 1)[1]
            old_body = old.split("\n---\n", 1)[1]
            self.assertEqual(new_body, old_body)


