"""Tests for install.sh: the runtime setting and the Claude Code install.

Every test runs install.sh with HOME, FORMIC_KIT_STATE_DIR, --config-dir and
--claude-dir pointing into temporary directories. Nothing touches the real
~/.config/opencode, ~/.claude or ~/.config/formic-kit.
"""
import os
import re
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INSTALL = ROOT / "install.sh"
MARKER = "# generated by formic-kit"
AGENTS = ("worker-haiku", "worker-sonnet", "formic-coordinator", "formic-ops")
SKILL_COUNT = len([d for d in (ROOT / "skills").iterdir() if d.is_dir()])


def snapshot(*dirs):
    """Map each path under the given dirs to its content, or 'link:<target>' for a link."""
    out = {}
    for base in dirs:
        base = Path(base)
        for p in sorted(base.rglob("*")):
            key = str(p)
            if p.is_symlink():
                out[key] = "link:" + os.readlink(p)
            elif p.is_file():
                out[key] = p.read_text()
    return out


class InstallTestCase(unittest.TestCase):
    def setUp(self):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.tmp = Path(tmp.name)
        self.home = self.tmp / "home"
        self.state = self.tmp / "state"
        self.oc = self.tmp / "opencode"
        self.cl = self.tmp / "claude"
        self.home.mkdir()

    def run_install(self, *args, dirs=True):
        env = dict(os.environ)
        env["HOME"] = str(self.home)
        env["FORMIC_KIT_STATE_DIR"] = str(self.state)
        cmd = ["bash", str(INSTALL)]
        cmd += list(args)
        if dirs:
            cmd += ["--config-dir", str(self.oc), "--claude-dir", str(self.cl)]
        return subprocess.run(cmd, capture_output=True, text=True, env=env, cwd=str(ROOT))

    def run_plain(self, *args):
        return self.run_install(*args, dirs=False)

    def claude_install(self, *extra):
        return self.run_install(
            "--runtime", "claude",
            "--coordinator-model", "coord-id", "--sonnet-model", "sonnet-id", "--haiku-model", "haiku-id",
            *extra)

    def opencode_install(self, *extra):
        return self.run_install(
            "--coordinator-model", "p/coord", "--sonnet-model", "p/sonnet", "--haiku-model", "p/haiku",
            *extra)

    def state_lines(self):
        return (self.state / "config").read_text().splitlines()


class TestOpencodeDefault(InstallTestCase):
    def test_default_runtime_is_opencode(self):
        r = self.opencode_install()
        self.assertEqual(r.returncode, 0, r.stderr)
        for name, model in (("worker-haiku", "p/haiku"), ("worker-sonnet", "p/sonnet"),
                            ("formic-coordinator", "p/coord")):
            text = (self.oc / "agents" / (name + ".md")).read_text()
            self.assertIn("model: " + model, text.splitlines())
            self.assertIn(MARKER, text)
        self.assertEqual(len(list((self.oc / "skills").iterdir())), SKILL_COUNT)
        lines = self.state_lines()
        self.assertIn("runtime=opencode", lines)
        # claude_dir is saved here only because the helper passes --claude-dir
        self.assertFalse([ln for ln in lines if ln.startswith("claude_") and "_model" in ln])
        self.assertFalse(self.cl.exists())

    def test_opencode_install_without_claude_dir_saves_no_claude_keys(self):
        env = dict(os.environ, HOME=str(self.home), FORMIC_KIT_STATE_DIR=str(self.state))
        r = subprocess.run(["bash", str(INSTALL), "--config-dir", str(self.oc),
                            "--coordinator-model", "p/c", "--sonnet-model", "p/s", "--haiku-model", "p/h"],
                           capture_output=True, text=True, env=env, cwd=str(ROOT))
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertFalse([ln for ln in self.state_lines() if ln.startswith("claude_")])
        self.assertFalse((self.home / ".claude").exists())

    def test_state_without_runtime_key_means_opencode(self):
        self.state.mkdir()
        (self.state / "config").write_text(
            "config_dir=%s\ncoordinator_model=p/coord\nsonnet_model=p/sonnet\nhaiku_model=p/haiku\n" % self.oc)
        r = self.run_plain()
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertTrue((self.oc / "agents" / "worker-sonnet.md").exists())
        self.assertIn("runtime=opencode", self.state_lines())

    def test_opencode_id_without_provider_fails(self):
        r = self.run_install("--haiku-model", "noprovider", "--sonnet-model", "p/s")
        self.assertNotEqual(r.returncode, 0)
        self.assertIn("provider/model", r.stderr)


class TestClaudeInstall(InstallTestCase):
    def test_claude_links_skills_and_writes_agents(self):
        r = self.claude_install()
        self.assertEqual(r.returncode, 0, r.stderr)
        links = [p for p in (self.cl / "skills").iterdir() if p.is_symlink()]
        self.assertEqual(len(links), SKILL_COUNT)
        for name in AGENTS:
            text = (self.cl / "agents" / (name + ".md")).read_text()
            self.assertIn(MARKER, text)
            self.assertFalse([ln for ln in text.splitlines() if ln.startswith("model:")])
            self.assertNotIn("coord-id", text)
        lines = self.state_lines()
        self.assertIn("runtime=claude", lines)
        self.assertIn("claude_dir=%s" % self.cl, lines)
        self.assertIn("claude_coordinator_model=coord-id", lines)
        self.assertIn("claude_sonnet_model=sonnet-id", lines)
        self.assertIn("claude_haiku_model=haiku-id", lines)
        self.assertFalse(self.oc.exists())
        self.assertIn("herdr integration install claude", r.stdout)

    def test_saved_runtime_is_used_without_flag(self):
        self.assertEqual(self.claude_install().returncode, 0)
        shutil.rmtree(self.cl)
        r = self.run_plain()  # no flags at all, as plugin/common.sh relink_if_moved does
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertEqual(len(list((self.cl / "skills").iterdir())), SKILL_COUNT)
        self.assertTrue((self.cl / "agents" / "worker-sonnet.md").exists())
        self.assertIn("runtime=claude", self.state_lines())
        self.assertIn("claude_sonnet_model=sonnet-id", self.state_lines())

    def test_runtime_flag_wins_over_saved(self):
        self.assertEqual(self.claude_install().returncode, 0)
        r = self.opencode_install("--runtime", "opencode")
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertTrue((self.oc / "agents" / "worker-haiku.md").exists())
        lines = self.state_lines()
        self.assertIn("runtime=opencode", lines)
        # the claude set is remembered while the opencode runtime is chosen
        self.assertIn("claude_sonnet_model=sonnet-id", lines)
        self.assertIn("sonnet_model=p/sonnet", lines)

    def test_model_sets_are_remembered_separately(self):
        self.assertEqual(self.opencode_install().returncode, 0)
        self.assertEqual(self.claude_install().returncode, 0)
        lines = self.state_lines()
        self.assertIn("sonnet_model=p/sonnet", lines)
        self.assertIn("claude_sonnet_model=sonnet-id", lines)

    def test_invalid_runtime_fails(self):
        r = self.run_install("--runtime", "bogus")
        self.assertNotEqual(r.returncode, 0)
        self.assertIn("error:", r.stderr)
        self.assertFalse((self.state / "config").exists())

    def test_runtime_needs_a_value(self):
        r = self.run_plain("--runtime")
        self.assertNotEqual(r.returncode, 0)
        self.assertIn("error:", r.stderr)

    def test_missing_worker_ids_exit_1_but_write_agents(self):
        r = self.run_install("--runtime", "claude", "--coordinator-model", "coord-id")
        self.assertEqual(r.returncode, 1)
        self.assertIn("--sonnet-model", r.stderr)
        self.assertIn("--haiku-model", r.stderr)
        for name in AGENTS:
            self.assertTrue((self.cl / "agents" / (name + ".md")).exists())
        self.assertIn("runtime=claude", self.state_lines())

    def test_missing_coordinator_id_is_only_a_note(self):
        r = self.run_install("--runtime", "claude", "--sonnet-model", "s", "--haiku-model", "h")
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertIn("note:", r.stdout)

    def test_claude_id_with_slash_warns_but_is_accepted(self):
        r = self.run_install("--runtime", "claude", "--sonnet-model", "prov/s", "--haiku-model", "h")
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertIn("no provider prefix", r.stderr)
        self.assertIn("claude_sonnet_model=prov/s", self.state_lines())


class TestPermissions(InstallTestCase):
    def test_default_saves_no_permissions_key_and_says_nothing(self):
        for install in (self.opencode_install, self.claude_install):
            r = install()
            self.assertEqual(r.returncode, 0, r.stderr)
            self.assertFalse([ln for ln in self.state_lines() if ln.startswith("permissions=")])
            self.assertNotIn("permissions", r.stdout)

    def test_auto_is_saved_and_remembered(self):
        r = self.opencode_install("--permissions", "auto")
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertIn("permissions=auto", self.state_lines())
        self.assertIn("--auto", r.stdout)
        r = self.run_install()
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertIn("permissions=auto", self.state_lines())

    def test_auto_with_claude_names_the_claude_flag(self):
        r = self.claude_install("--permissions", "auto")
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertIn("permissions=auto", self.state_lines())
        self.assertIn("--dangerously-skip-permissions", r.stdout)

    def test_ask_turns_auto_off(self):
        self.assertEqual(self.opencode_install("--permissions", "auto").returncode, 0)
        r = self.run_install("--permissions", "ask")
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertFalse([ln for ln in self.state_lines() if ln.startswith("permissions=")])

    def test_unknown_saved_value_means_ask(self):
        self.assertEqual(self.opencode_install().returncode, 0)
        with open(self.state / "config", "a") as f:
            f.write("permissions=yolo\n")
        r = self.run_install()
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertFalse([ln for ln in self.state_lines() if ln.startswith("permissions=")])

    def test_invalid_value_fails(self):
        r = self.run_install("--permissions", "always")
        self.assertNotEqual(r.returncode, 0)
        self.assertIn("--permissions must be ask or auto", r.stderr)

    def test_permissions_needs_a_value(self):
        r = self.run_plain("--permissions")
        self.assertNotEqual(r.returncode, 0)
        self.assertIn("needs a value", r.stderr)

    def test_agent_files_are_the_same_in_both_modes(self):
        self.assertEqual(self.opencode_install().returncode, 0)
        before = snapshot(self.oc)
        self.assertEqual(self.opencode_install("--permissions", "auto").returncode, 0)
        self.assertEqual(before, snapshot(self.oc))


class TestIdempotentAndSafe(InstallTestCase):
    def check_second_run_changes_nothing(self, install):
        self.assertEqual(install().returncode, 0)
        before = snapshot(self.oc, self.cl, self.state)
        r = install()
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertEqual(before, snapshot(self.oc, self.cl, self.state))

    def test_second_run_claude(self):
        self.check_second_run_changes_nothing(self.claude_install)

    def test_second_run_opencode(self):
        self.check_second_run_changes_nothing(self.opencode_install)

    def test_second_run_with_auto_permissions(self):
        self.check_second_run_changes_nothing(lambda: self.opencode_install("--permissions", "auto"))

    def test_foreign_agent_is_kept(self):
        (self.cl / "agents").mkdir(parents=True)
        foreign = self.cl / "agents" / "worker-sonnet.md"
        foreign.write_text("my own agent\n")
        r = self.claude_install()
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertIn("kept your existing", r.stdout)
        self.assertEqual(foreign.read_text(), "my own agent\n")
        self.assertFalse(foreign.with_name("worker-sonnet.md.bak").exists())
        self.assertNotIn(str(foreign), (self.state / "manifest").read_text().splitlines())

    def test_force_replaces_foreign_agent_and_keeps_bak(self):
        (self.cl / "agents").mkdir(parents=True)
        foreign = self.cl / "agents" / "worker-sonnet.md"
        foreign.write_text("my own agent\n")
        r = self.claude_install("--force")
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertIn(MARKER, foreign.read_text())
        self.assertEqual((self.cl / "agents" / "worker-sonnet.md.bak").read_text(), "my own agent\n")
        # a second forced run must not overwrite the backup with kit content
        self.assertEqual(self.claude_install("--force").returncode, 0)
        self.assertEqual((self.cl / "agents" / "worker-sonnet.md.bak").read_text(), "my own agent\n")

    def test_foreign_skill_is_kept(self):
        (self.cl / "skills" / "formic-brief").mkdir(parents=True)
        r = self.claude_install()
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertIn("skipped", r.stderr)
        self.assertFalse((self.cl / "skills" / "formic-brief").is_symlink())


class TestUninstall(InstallTestCase):
    def test_uninstall_claude(self):
        (self.cl / "agents").mkdir(parents=True)
        foreign = self.cl / "agents" / "worker-sonnet.md"
        foreign.write_text("my own agent\n")
        self.assertEqual(self.claude_install().returncode, 0)
        r = self.run_plain("uninstall")
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertEqual([p for p in (self.cl / "skills").iterdir()], [])
        self.assertFalse((self.cl / "agents" / "worker-haiku.md").exists())
        self.assertFalse((self.cl / "agents" / "formic-coordinator.md").exists())
        self.assertEqual(foreign.read_text(), "my own agent\n")
        self.assertFalse(self.state.exists())

    def test_uninstall_leaves_an_edited_agent(self):
        self.assertEqual(self.claude_install().returncode, 0)
        agent = self.cl / "agents" / "worker-haiku.md"
        agent.write_text("replaced by the user\n")
        r = self.run_plain("uninstall")
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertEqual(agent.read_text(), "replaced by the user\n")

    def test_uninstall_removes_both_runtimes(self):
        self.assertEqual(self.opencode_install().returncode, 0)
        self.assertEqual(self.claude_install().returncode, 0)
        r = self.run_plain("uninstall")
        self.assertEqual(r.returncode, 0, r.stderr)
        for base in (self.oc, self.cl):
            self.assertEqual([p for p in (base / "skills").iterdir()], [])
            for name in AGENTS:
                self.assertFalse((base / "agents" / (name + ".md")).exists())
        self.assertFalse(self.state.exists())


