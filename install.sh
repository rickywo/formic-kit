#!/usr/bin/env bash
# formic-kit installer.
#
#   ./install.sh [install] [options]   link skills and write agent profiles for this machine
#   ./install.sh init [project-dir]    set up a project to use the board
#   ./install.sh doctor [project-dir]  check that everything needed is in place
#   ./install.sh uninstall             remove what install created
#
# Run ./install.sh --help for options.

set -euo pipefail

KIT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
KIT_VERSION="$(cat "$KIT_DIR/VERSION" 2>/dev/null || echo unknown)"
STATE_DIR="${FORMIC_KIT_STATE_DIR:-$HOME/.config/formic-kit}"
STATE_FILE="$STATE_DIR/config"
MANIFEST="$STATE_DIR/manifest"
MARKER="# generated by formic-kit"
AGENTS_HEADING="## Task workflow (formic-kit)"

RUNTIME=""
CONFIG_DIR=""
COORDINATOR_MODEL=""
SONNET_MODEL=""
HAIKU_MODEL=""
CLAUDE_DIR=""
CLAUDE_COORDINATOR_MODEL=""
CLAUDE_SONNET_MODEL=""
CLAUDE_HAIKU_MODEL=""
PERMISSIONS=""
# Model flags are held here until the runtime is known (it may come from the saved state).
FLAG_COORDINATOR_MODEL=""
FLAG_SONNET_MODEL=""
FLAG_HAIKU_MODEL=""
FORCE=0
LOCAL_SKILLS=0

say()  { printf '%s\n' "$*"; }
warn() { printf 'warning: %s\n' "$*" >&2; }
die()  { printf 'error: %s\n' "$*" >&2; exit 1; }

usage() {
  cat <<EOF
formic-kit $KIT_VERSION

Usage:
  ./install.sh [install] [--runtime opencode|claude] [--coordinator-model ID]
                         [--sonnet-model ID] [--haiku-model ID]
                         [--config-dir DIR] [--claude-dir DIR] [--force]
                         [--permissions ask|auto]
  ./install.sh init [PROJECT_DIR] [--local-skills]
  ./install.sh doctor [PROJECT_DIR]
  ./install.sh uninstall

install
  Links every kit skill into <config-dir>/skills and writes four agent profiles into
  <config-dir>/agents: worker-haiku, worker-sonnet, formic-coordinator and formic-ops.
  formic-ops is a work assistant across projects; it uses the coordinator model.
  Model ids use opencode's provider/model form; list them with 'opencode models'.
  The ids are remembered, so later runs need no flags.
  A file or link that install did not create is left alone unless --force is given;
  with --force the existing file is first copied to <name>.bak.

  --config-dir DIR   opencode config directory (default: ~/.config/opencode)

  --runtime RT       which tool runs the coordinator and the workers: opencode (the default)
                     or claude (Claude Code). The choice is remembered, so later runs need
                     no flag. With claude, install links the skills into <claude-dir>/skills
                     and writes the same four agents into <claude-dir>/agents.
  --claude-dir DIR   Where the kit installs skills and agents for Claude Code (default:
                     ~/.claude); remembered. This can be a project's .claude folder.
                     It is not where transcripts are read: the dispatch scripts look
                     in \$FORMIC_CLAUDE_DIR, else \$CLAUDE_CONFIG_DIR, else ~/.claude.

  Claude Code model ids have no provider prefix (for example the id that
  'claude --model' accepts). They are remembered separately from the opencode ids, so
  switching runtime does not lose the other set. They are not written into the Claude Code
  agent files; the coordinator passes them to Claude Code with --model. Workers need
  --sonnet-model and --haiku-model; --coordinator-model is optional.

  --permissions MODE How the coordinator and the workers are started: ask (the default) or
                     auto. The choice is remembered. With ask, a permission prompt in a
                     worker's pane is shown to you and nothing is answered for you. With auto,
                     the kit starts opencode with --auto and Claude Code with
                     --dangerously-skip-permissions, so the agents run commands, edit files
                     and reach outside the project without asking. Use auto only where that
                     is acceptable. Pass --permissions ask to go back.

init
  Creates .formic/board.json and .formic/project.json in the project if they are absent
  and adds a short section to its AGENTS.md. Never changes an existing board.

  With the claude runtime it also creates <project>/CLAUDE.md containing '@AGENTS.md' if the
  project has none (an existing CLAUDE.md is left alone), because Claude Code reads CLAUDE.md,
  not AGENTS.md.

  --local-skills     also link the skills into <project>/.opencode/skills (or
                     <project>/.claude/skills with the claude runtime), for a machine
                     where 'install' has not been run

doctor
  Checks the tools, the skill links and the agents, and the project if one is given
  or the current directory has a .formic folder. Exits 1 if anything required is missing.
  It checks the configured runtime (the saved one, or --runtime). With claude it checks
  claude, the claude herdr integration, <claude-dir>/skills, the agent files in
  <claude-dir>/agents and the saved Claude Code model ids.

uninstall
  Removes the links and agent files that install created. Projects are not touched.
EOF
}

# ------------------------------------------------------------------ state

load_state() {
  [ -f "$STATE_FILE" ] || return 0
  local key value
  while IFS='=' read -r key value; do
    case "$key" in
      config_dir)        [ -n "$CONFIG_DIR" ]        || CONFIG_DIR="$value" ;;
      coordinator_model) [ -n "$COORDINATOR_MODEL" ] || COORDINATOR_MODEL="$value" ;;
      sonnet_model)      [ -n "$SONNET_MODEL" ]      || SONNET_MODEL="$value" ;;
      haiku_model)       [ -n "$HAIKU_MODEL" ]       || HAIKU_MODEL="$value" ;;
      runtime)           [ -n "$RUNTIME" ]           || RUNTIME="$value" ;;
      claude_dir)        [ -n "$CLAUDE_DIR" ]        || CLAUDE_DIR="$value" ;;
      claude_coordinator_model) [ -n "$CLAUDE_COORDINATOR_MODEL" ] || CLAUDE_COORDINATOR_MODEL="$value" ;;
      claude_sonnet_model)      [ -n "$CLAUDE_SONNET_MODEL" ]      || CLAUDE_SONNET_MODEL="$value" ;;
      claude_haiku_model)       [ -n "$CLAUDE_HAIKU_MODEL" ]       || CLAUDE_HAIKU_MODEL="$value" ;;
      permissions)       [ -n "$PERMISSIONS" ]       || PERMISSIONS="$value" ;;
    esac
  done < "$STATE_FILE"
}

# Settle the runtime and hand each model flag to the variables of that runtime.
# Runs after load_state, so a flag wins over a saved value and a saved runtime is honoured.
resolve_settings() {
  [ -n "$RUNTIME" ] || RUNTIME="opencode"
  case "$RUNTIME" in
    opencode|claude) ;;
    *) die "--runtime must be opencode or claude, not '$RUNTIME'" ;;
  esac
  # Anything but auto, including a missing or damaged saved value, means ask.
  [ "$PERMISSIONS" = "auto" ] || PERMISSIONS="ask"
  if [ "$RUNTIME" = "claude" ]; then
    if [ -n "$FLAG_COORDINATOR_MODEL" ]; then CLAUDE_COORDINATOR_MODEL="$FLAG_COORDINATOR_MODEL"; fi
    if [ -n "$FLAG_SONNET_MODEL" ]; then CLAUDE_SONNET_MODEL="$FLAG_SONNET_MODEL"; fi
    if [ -n "$FLAG_HAIKU_MODEL" ]; then CLAUDE_HAIKU_MODEL="$FLAG_HAIKU_MODEL"; fi
  else
    if [ -n "$FLAG_COORDINATOR_MODEL" ]; then COORDINATOR_MODEL="$FLAG_COORDINATOR_MODEL"; fi
    if [ -n "$FLAG_SONNET_MODEL" ]; then SONNET_MODEL="$FLAG_SONNET_MODEL"; fi
    if [ -n "$FLAG_HAIKU_MODEL" ]; then HAIKU_MODEL="$FLAG_HAIKU_MODEL"; fi
  fi
}

save_state() {
  mkdir -p "$STATE_DIR"
  {
    printf 'config_dir=%s\n' "$CONFIG_DIR"
    printf 'coordinator_model=%s\n' "$COORDINATOR_MODEL"
    printf 'sonnet_model=%s\n' "$SONNET_MODEL"
    printf 'haiku_model=%s\n' "$HAIKU_MODEL"
    printf 'runtime=%s\n' "$RUNTIME"
    if [ -n "$CLAUDE_DIR" ]; then printf 'claude_dir=%s\n' "$CLAUDE_DIR"; fi
    if [ -n "$CLAUDE_COORDINATOR_MODEL" ]; then printf 'claude_coordinator_model=%s\n' "$CLAUDE_COORDINATOR_MODEL"; fi
    if [ -n "$CLAUDE_SONNET_MODEL" ]; then printf 'claude_sonnet_model=%s\n' "$CLAUDE_SONNET_MODEL"; fi
    if [ -n "$CLAUDE_HAIKU_MODEL" ]; then printf 'claude_haiku_model=%s\n' "$CLAUDE_HAIKU_MODEL"; fi
    # Written only for auto, so the settings file of an install that never opted in is unchanged.
    if [ "$PERMISSIONS" = "auto" ]; then printf 'permissions=auto\n'; fi
    printf 'kit_dir=%s\n' "$KIT_DIR"
    printf 'kit_version=%s\n' "$KIT_VERSION"
  } > "$STATE_FILE"
}

record() {
  mkdir -p "$STATE_DIR"
  touch "$MANIFEST"
  grep -qxF "$1" "$MANIFEST" || printf '%s\n' "$1" >> "$MANIFEST"
}

# ---------------------------------------------------------------- install

link_skill() {
  local src="$1" dest="$2/$(basename "$1")"
  if [ -L "$dest" ]; then
    if [ "$(readlink "$dest")" = "$src" ]; then
      return 0
    fi
    case "$(readlink "$dest")" in
      */skills/formic-*) ;;  # an older kit location: safe to repoint
      *) if [ "$FORCE" -ne 1 ]; then warn "skipped $dest: a link to somewhere else exists (use --force)"; return 1; fi ;;
    esac
    rm "$dest"
  elif [ -e "$dest" ]; then
    if [ "$FORCE" -ne 1 ]; then warn "skipped $dest: it exists and is not a link (use --force)"; return 1; fi
    rm -rf "$dest.bak"; mv "$dest" "$dest.bak"; say "  kept the old $dest as $dest.bak"
  fi
  ln -s "$src" "$dest"
}

link_skills() {
  local target="$1" n=0 skipped=0 d
  mkdir -p "$target"
  for d in "$KIT_DIR"/skills/*/; do
    d="${d%/}"
    if link_skill "$d" "$target"; then
      n=$((n + 1)); [ "$2" = "record" ] && record "$target/$(basename "$d")"
    else
      skipped=$((skipped + 1))
    fi
  done
  say "skills: $n linked into $target"
  [ "$skipped" -eq 0 ] || warn "$skipped skills were skipped"
}

write_agent() {
  local name="$1" model="$2" flag="$3"
  local tmpl="$KIT_DIR/agents/$name.md.tmpl" dest="$CONFIG_DIR/agents/$name.md"
  if [ -e "$dest" ] && ! grep -qF "$MARKER" "$dest"; then
    if [ "$FORCE" -ne 1 ]; then
      say "agent $name: kept your existing $dest (not created by formic-kit; use --force to replace it)"
      return 0
    fi
    cp "$dest" "$dest.bak"; say "agent $name: kept the old file as $dest.bak"
  fi
  if [ -z "$model" ]; then
    if [ -e "$dest" ]; then
      say "agent $name: left as it is (no model given)"
    else
      if [ "$name" = "formic-coordinator" ] || [ "$name" = "formic-ops" ]; then
        say "agent $name: not written (optional). Pass $flag <provider/model> to add it"
      else
        warn "agent $name: not written. Pass $flag <provider/model>"
        MISSING_AGENTS=1
      fi
    fi
    return 0
  fi
  case "$model" in
    */*) ;;
    *) die "$flag '$model' is not in provider/model form" ;;
  esac
  mkdir -p "$CONFIG_DIR/agents"
  # Models can contain characters that are special to sed, so substitute with awk.
  awk -v model="$model" '{ gsub(/\{\{MODEL\}\}/, model); print }' "$tmpl" > "$dest.tmp"
  mv "$dest.tmp" "$dest"
  record "$dest"
  say "agent $name: written with model $model"
}

# Claude Code agent files carry no model id: the coordinator passes --model when it starts one.
write_claude_agent() {
  local name="$1"
  local tmpl="$KIT_DIR/agents/$name.claude.md.tmpl" dest="$CLAUDE_DIR/agents/$name.md"
  if [ -e "$dest" ] && ! grep -qF "$MARKER" "$dest"; then
    if [ "$FORCE" -ne 1 ]; then
      say "agent $name: kept your existing $dest (not created by formic-kit; use --force to replace it)"
      return 0
    fi
    cp "$dest" "$dest.bak"; say "agent $name: kept the old file as $dest.bak"
  fi
  mkdir -p "$CLAUDE_DIR/agents"
  if [ -f "$dest" ] && cmp -s "$tmpl" "$dest"; then
    say "agent $name: up to date"
  else
    cp "$tmpl" "$dest.tmp"
    mv "$dest.tmp" "$dest"
    say "agent $name: written"
  fi
  record "$dest"
}

# Says nothing for ask, so the output of an install that never opted in is unchanged.
say_permissions() {
  [ "$PERMISSIONS" = "auto" ] || return 0
  if [ "$RUNTIME" = "claude" ]; then
    say "permissions: auto. The coordinator and the workers start with --dangerously-skip-permissions"
  else
    say "permissions: auto. The coordinator and the workers start with --auto"
  fi
}

cmd_install_claude() {
  [ -n "$CLAUDE_DIR" ] || CLAUDE_DIR="$HOME/.claude"
  say "formic-kit $KIT_VERSION -> $CLAUDE_DIR (Claude Code)"
  MISSING_AGENTS=0
  local flag id
  for flag in "--coordinator-model|$CLAUDE_COORDINATOR_MODEL" "--sonnet-model|$CLAUDE_SONNET_MODEL" "--haiku-model|$CLAUDE_HAIKU_MODEL"; do
    id="${flag#*|}"
    case "$id" in
      */*) warn "${flag%%|*} '$id' contains a '/': Claude Code model ids have no provider prefix" ;;
    esac
  done
  link_skills "$CLAUDE_DIR/skills" record
  write_claude_agent worker-haiku
  write_claude_agent worker-sonnet
  write_claude_agent formic-coordinator
  write_claude_agent formic-ops
  if [ -z "$CLAUDE_SONNET_MODEL" ]; then
    warn "claude sonnet model id is not set. Pass --sonnet-model <id>"
    MISSING_AGENTS=1
  fi
  if [ -z "$CLAUDE_HAIKU_MODEL" ]; then
    warn "claude haiku model id is not set. Pass --haiku-model <id>"
    MISSING_AGENTS=1
  fi
  if [ -z "$CLAUDE_COORDINATOR_MODEL" ]; then
    say "note: no coordinator model id; the coordinator starts on Claude Code's default model. Pass --coordinator-model <id> to set one"
  fi
  save_state
  say_permissions
  say ""
  if [ "$MISSING_AGENTS" -eq 1 ]; then
    say "Some model ids are missing. Rerun with the model flags above, then run: ./install.sh doctor"
    exit 1
  else
    say "Next: 'herdr integration install claude' if it is not installed yet, then ./install.sh doctor"
    say "Then in each project: $KIT_DIR/install.sh init ."
  fi
}

cmd_install() {
  if [ "$RUNTIME" = "claude" ]; then cmd_install_claude; return; fi
  [ -n "$CONFIG_DIR" ] || CONFIG_DIR="$HOME/.config/opencode"
  say "formic-kit $KIT_VERSION -> $CONFIG_DIR"
  MISSING_AGENTS=0
  link_skills "$CONFIG_DIR/skills" record
  write_agent worker-haiku "$HAIKU_MODEL" --haiku-model
  write_agent worker-sonnet "$SONNET_MODEL" --sonnet-model
  write_agent formic-coordinator "$COORDINATOR_MODEL" --coordinator-model
  write_agent formic-ops "$COORDINATOR_MODEL" --coordinator-model
  save_state
  say_permissions
  say ""
  if [ "$MISSING_AGENTS" -eq 1 ]; then
    say "Some agents are missing. Rerun with the model flags above, then run: ./install.sh doctor"
    exit 1
  else
    say "Next: 'herdr integration install opencode' if it is not installed yet, then ./install.sh doctor"
    say "Then in each project: $KIT_DIR/install.sh init ."
  fi
}

# ------------------------------------------------------------------- init

cmd_init() {
  local project="${1:-.}"
  [ -d "$project" ] || die "$project is not a directory"
  project="$(cd "$project" && pwd)"
  command -v python3 >/dev/null || die "python3 is required"
  git -C "$project" rev-parse --is-inside-work-tree >/dev/null 2>&1 \
    || warn "$project is not a git repository; the coordinator needs one to run tasks"

  if [ -f "$project/.formic/board.json" ]; then
    say "board: $project/.formic/board.json already exists, left as it is"
  else
    python3 "$KIT_DIR/skills/formic-board/scripts/board.py" --root "$project" init >/dev/null
    say "board: created $project/.formic/board.json"
  fi

  if [ -f "$project/.formic/project.json" ]; then
    say "settings: $project/.formic/project.json already exists, left as it is"
  else
    cp "$KIT_DIR/templates/project.json" "$project/.formic/project.json"
    say "settings: created $project/.formic/project.json  <- fill in the check commands"
  fi

  if [ -f "$project/AGENTS.md" ] && grep -qF "$AGENTS_HEADING" "$project/AGENTS.md"; then
    say "AGENTS.md: already has the formic-kit section"
  else
    [ -f "$project/AGENTS.md" ] && printf '\n\n' >> "$project/AGENTS.md"
    cat "$KIT_DIR/templates/AGENTS-section.md" >> "$project/AGENTS.md"
    say "AGENTS.md: added the formic-kit section"
  fi

  # Claude Code reads CLAUDE.md, not AGENTS.md; a CLAUDE.md that imports AGENTS.md fixes that.
  if [ "$RUNTIME" = "claude" ]; then
    if [ -e "$project/CLAUDE.md" ]; then
      say "CLAUDE.md: already exists, left as it is"
    else
      printf '@AGENTS.md\n' > "$project/CLAUDE.md"
      say "CLAUDE.md: created with @AGENTS.md"
    fi
  fi

  if [ "$LOCAL_SKILLS" -eq 1 ]; then
    if [ "$RUNTIME" = "claude" ]; then
      link_skills "$project/.claude/skills" norecord
    else
      link_skills "$project/.opencode/skills" norecord
    fi
  fi

  say ""
  say "Next: edit .formic/project.json (typecheck, build and test commands, guideline file),"
  if [ "$RUNTIME" = "claude" ]; then
    say "then start Claude Code inside herdr in $project and ask it to create or run tasks."
    say "The first Claude Code start in a new project asks whether you trust the folder; answer it yourself."
  else
    say "then start opencode inside herdr in $project and ask it to create or run tasks."
    say "The first opencode start in a new project takes about a minute."
  fi
}

# ----------------------------------------------------------------- doctor

FAILS=0
ok()   { printf '  ok    %s\n' "$*"; }
bad()  { printf '  FAIL  %s\n' "$*"; FAILS=$((FAILS + 1)); }
note() { printf '  note  %s\n' "$*"; }

cmd_doctor() {
  local project="${1:-}"
  [ -n "$CONFIG_DIR" ] || CONFIG_DIR="$HOME/.config/opencode"
  [ -n "$CLAUDE_DIR" ] || CLAUDE_DIR="$HOME/.claude"
  # The checks follow the configured runtime. For opencode every line is as it always was.
  local skills_root="$CONFIG_DIR/skills" local_dir=".opencode" tools="opencode herdr python3 git"
  if [ "$RUNTIME" = "claude" ]; then
    skills_root="$CLAUDE_DIR/skills"; local_dir=".claude"; tools="claude herdr python3 git"
  fi
  say "formic-kit $KIT_VERSION doctor"

  say "Tools"
  local t
  for t in $tools; do
    if command -v "$t" >/dev/null; then ok "$t found"; else bad "$t is not installed or not on PATH"; fi
  done
  if command -v herdr >/dev/null; then
    local st
    st="$(herdr integration status 2>/dev/null | grep "^$RUNTIME:" || true)"
    case "$st" in
      *current*) ok "herdr $RUNTIME integration: ${st#"$RUNTIME": }" ;;
      "")        bad "herdr $RUNTIME integration status unknown; run: herdr integration install $RUNTIME" ;;
      *)         bad "herdr $RUNTIME integration: ${st#"$RUNTIME": }; run: herdr integration install $RUNTIME" ;;
    esac
    if [ "${HERDR_ENV:-}" = 1 ]; then ok "running inside herdr"; else note "not inside a herdr pane; the coordinator must be started inside herdr"; fi
  fi

  if [ "$PERMISSIONS" = "auto" ]; then
    say "Permissions"
    if [ "$RUNTIME" = "claude" ]; then note "auto: agents start with --dangerously-skip-permissions and are not asked before they act"
    else note "auto: agents start with --auto and are not asked before they act"; fi
  fi

  say "Skills"
  local total=0 linked=0 d dest
  for d in "$KIT_DIR"/skills/*/; do
    d="${d%/}"; total=$((total + 1))
    for dest in "$skills_root/$(basename "$d")" ${project:+"$project/$local_dir/skills/$(basename "$d")"} "$local_dir/skills/$(basename "$d")"; do
      if [ -f "$dest/SKILL.md" ]; then linked=$((linked + 1)); break; fi
    done
  done
  if [ "$linked" -eq "$total" ]; then ok "$linked of $total kit skills are reachable"
  else bad "$linked of $total kit skills are reachable; run ./install.sh (or init --local-skills)"; fi
  local broken=0 l
  if [ -d "$skills_root" ]; then
    for l in "$skills_root"/formic-*; do
      [ -L "$l" ] && [ ! -e "$l" ] && { broken=$((broken + 1)); bad "broken link $l"; }
    done
  fi
  [ "$broken" -eq 0 ] || note "broken links usually mean the kit folder moved; rerun ./install.sh"

  say "Agents"
  if [ "$RUNTIME" = "claude" ]; then
    # Only look at the files: the doctor never starts claude.
    local ca cf
    for ca in worker-haiku worker-sonnet; do
      cf="$CLAUDE_DIR/agents/$ca.md"
      if [ -f "$cf" ]; then
        ok "$ca"
        grep -qF "$MARKER" "$cf" || note "$ca is your own agent file, not the kit's"
      else
        bad "agent $ca not found at $cf; run ./install.sh --runtime claude with its model flag"
      fi
    done
    cf="$CLAUDE_DIR/agents/formic-coordinator.md"
    if [ -f "$cf" ]; then
      ok "formic-coordinator"
      grep -qF "$MARKER" "$cf" || note "formic-coordinator is your own agent file, not the kit's"
    else
      note "formic-coordinator agent not installed (optional): run ./install.sh --runtime claude"
    fi
    cf="$CLAUDE_DIR/agents/formic-ops.md"
    if [ -f "$cf" ]; then
      ok "formic-ops"
      grep -qF "$MARKER" "$cf" || note "formic-ops is your own agent file, not the kit's"
    else
      note "formic-ops agent not installed (optional): run ./install.sh --runtime claude"
    fi

    say "Models"
    if [ -z "$CLAUDE_HAIKU_MODEL" ]; then bad "claude haiku model id is not saved; run ./install.sh --runtime claude --haiku-model <id>"
    else ok "claude haiku model: $CLAUDE_HAIKU_MODEL"; fi
    if [ -z "$CLAUDE_SONNET_MODEL" ]; then bad "claude sonnet model id is not saved; run ./install.sh --runtime claude --sonnet-model <id>"
    else ok "claude sonnet model: $CLAUDE_SONNET_MODEL"; fi
    if [ -z "$CLAUDE_COORDINATOR_MODEL" ]; then note "no claude coordinator model id saved; the coordinator starts on Claude Code's default model"
    else ok "claude coordinator model: $CLAUDE_COORDINATOR_MODEL"; fi
  else
    if command -v opencode >/dev/null; then
      # Write the list to a file: opencode cuts long output short when it is written to a pipe.
      local list a listfile
      listfile="$(mktemp)"
      OPENCODE_CONFIG_DIR="$CONFIG_DIR" opencode agent list > "$listfile" 2>/dev/null || true
      list="$(grep -E '^[A-Za-z0-9_/-]+ \(' "$listfile" || true)"
      rm -f "$listfile"
      for a in worker-haiku worker-sonnet; do
        if grep -q "^$a " <<< "$list"; then
          local f="$CONFIG_DIR/agents/$a.md" m=""
          [ -f "$f" ] && m="$(awk '/^model:/ { sub(/^model: */, ""); print; exit }' "$f")"
          ok "$a${m:+ ($m)}"
          [ -f "$f" ] && ! grep -qF "$MARKER" "$f" && note "$a is your own profile, not the kit's; it sets no explicit edit and shell permissions"
        else
          bad "agent $a not found; run ./install.sh with its model flag"
        fi
      done
      if grep -q "^formic-coordinator " <<< "$list"; then ok "formic-coordinator"
      else note "formic-coordinator agent not installed (optional): pass --coordinator-model to install"; fi
      if grep -q "^formic-ops " <<< "$list"; then ok "formic-ops"
      else note "formic-ops agent not installed (optional): pass --coordinator-model to install"; fi
    fi
  fi

  [ -n "$project" ] || { [ -d .formic ] && project="."; }
  if [ -n "$project" ]; then
    project="$(cd "$project" && pwd)"
    say "Project $project"
    if git -C "$project" rev-parse --is-inside-work-tree >/dev/null 2>&1; then ok "git repository"; else bad "not a git repository"; fi
    if [ -f "$project/.formic/board.json" ]; then
      local v
      if v="$(python3 "$KIT_DIR/skills/formic-board/scripts/board.py" --root "$project" validate 2>&1)"; then ok "board: ${v#OK: }"
      else bad "board: $(printf '%s' "$v" | head -3 | tr '\n' ' ')"; fi
    else
      bad "no .formic/board.json; run ./install.sh init $project"
    fi
    if [ -f "$project/.formic/project.json" ]; then
      local c
      c="$(python3 - "$project/.formic/project.json" <<'PY'
import json, sys
try:
    d = json.load(open(sys.argv[1]))
except Exception as e:
    print("invalid: %s" % e); sys.exit(0)
c = d.get("commands") or {}
missing = [k for k in ("typecheck", "test") if not c.get(k)]
print("missing: " + ", ".join(missing) if missing else "ok")
PY
)"
      case "$c" in
        ok)        ok "project.json has typecheck and test commands" ;;
        missing*)  note "project.json ${c}; the quality gate cannot run those checks until they are set" ;;
        *)         bad "project.json $c" ;;
      esac
    else
      bad "no .formic/project.json; run ./install.sh init $project"
    fi
    if [ -f "$project/AGENTS.md" ] && grep -qF "$AGENTS_HEADING" "$project/AGENTS.md"; then ok "AGENTS.md has the formic-kit section"
    else note "AGENTS.md has no formic-kit section; run ./install.sh init $project"; fi
    if [ "$RUNTIME" = "claude" ]; then
      if [ ! -f "$project/CLAUDE.md" ]; then note "no CLAUDE.md; Claude Code will not read AGENTS.md; run ./install.sh init $project"
      elif grep -qF "@AGENTS.md" "$project/CLAUDE.md"; then ok "CLAUDE.md imports AGENTS.md"
      else note "CLAUDE.md exists but does not import AGENTS.md"; fi
    fi
  fi

  say ""
  if [ "$FAILS" -eq 0 ]; then say "All required checks passed."; else say "$FAILS required check(s) failed."; exit 1; fi
}

# -------------------------------------------------------------- uninstall

cmd_uninstall() {
  [ -f "$MANIFEST" ] || { say "nothing to remove: no install recorded in $STATE_DIR"; return 0; }
  local path n=0
  while IFS= read -r path; do
    [ -n "$path" ] || continue
    if [ -L "$path" ]; then
      rm "$path"; n=$((n + 1))
    elif [ -f "$path" ] && grep -qF "$MARKER" "$path"; then
      rm "$path"; n=$((n + 1))
    elif [ -e "$path" ]; then
      warn "left $path: it is no longer the file install created"
    fi
  done < "$MANIFEST"
  rm -f "$MANIFEST" "$STATE_FILE"
  rmdir "$STATE_DIR" 2>/dev/null || true
  say "removed $n links and agent files. Projects and their .formic folders were not touched."
}

