POSITIONAL=()
while [ $# -gt 0 ]; do
  case "$1" in
    --coordinator-model) [ $# -ge 2 ] || die "$1 needs a value"; FLAG_COORDINATOR_MODEL="$2"; shift 2 ;;
    --sonnet-model)      [ $# -ge 2 ] || die "$1 needs a value"; FLAG_SONNET_MODEL="$2"; shift 2 ;;
    --haiku-model)       [ $# -ge 2 ] || die "$1 needs a value"; FLAG_HAIKU_MODEL="$2"; shift 2 ;;
    --config-dir)        [ $# -ge 2 ] || die "$1 needs a value"; CONFIG_DIR="$2"; shift 2 ;;
    --claude-dir)        [ $# -ge 2 ] || die "$1 needs a value"; CLAUDE_DIR="$2"; shift 2 ;;
    --runtime)           [ $# -ge 2 ] || die "$1 needs a value"
                         case "$2" in
                           opencode|claude) RUNTIME="$2" ;;
                           *) die "--runtime must be opencode or claude, not '$2'" ;;
                         esac
                         shift 2 ;;
    --permissions)       [ $# -ge 2 ] || die "$1 needs a value"
                         case "$2" in
                           ask|auto) PERMISSIONS="$2" ;;
                           *) die "--permissions must be ask or auto, not '$2'" ;;
                         esac
                         shift 2 ;;
    --force)             FORCE=1; shift ;;
    --local-skills)      LOCAL_SKILLS=1; shift ;;
    -h|--help)           usage; exit 0 ;;
    -*)                  die "unknown option $1 (see --help)" ;;
    *)                   POSITIONAL+=("$1"); shift ;;
  esac
done

