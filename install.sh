#!/usr/bin/env bash
# formic-kit installer.
#
#   ./install.sh [install] [options]   link skills and write agent profiles for this machine
#   ./install.sh init [project-dir]    set up a project to use the board
#   ./install.sh doctor [project-dir]  check that everything needed is in place
#   ./install.sh uninstall             remove what install created
#
# Run ./install.sh --help for options.

set -euo pipefail

KIT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
KIT_VERSION="$(cat "$KIT_DIR/VERSION" 2>/dev/null || echo unknown)"
STATE_DIR="${FORMIC_KIT_STATE_DIR:-$HOME/.config/formic-kit}"
STATE_FILE="$STATE_DIR/config"
MANIFEST="$STATE_DIR/manifest"
MARKER="# generated by formic-kit"
AGENTS_HEADING="## Task workflow (formic-kit)"

CONFIG_DIR=""
COORDINATOR_MODEL=""
SONNET_MODEL=""
HAIKU_MODEL=""
FORCE=0
LOCAL_SKILLS=0

say()  { printf '%s\n' "$*"; }
warn() { printf 'warning: %s\n' "$*" >&2; }
die()  { printf 'error: %s\n' "$*" >&2; exit 1; }

usage() {
  cat <<EOF
formic-kit $KIT_VERSION

Usage:
  ./install.sh [install] [--coordinator-model ID] [--sonnet-model ID] [--haiku-model ID]
                         [--config-dir DIR] [--force]
  ./install.sh init [PROJECT_DIR] [--local-skills]
  ./install.sh doctor [PROJECT_DIR]
  ./install.sh uninstall

install
  Links every kit skill into <config-dir>/skills and writes three agent profiles into
  <config-dir>/agents: worker-haiku, worker-sonnet and formic-coordinator.
  Model ids use opencode's provider/model form; list them with 'opencode models'.
  The ids are remembered, so later runs need no flags.
  A file or link that install did not create is left alone unless --force is given;
  with --force the existing file is first copied to <name>.bak.

  --config-dir DIR   opencode config directory (default: ~/.config/opencode)

init
  Creates .formic/board.json and .formic/project.json in the project if they are absent
  and adds a short section to its AGENTS.md. Never changes an existing board.

  --local-skills     also link the skills into <project>/.opencode/skills, for a machine
                     where 'install' has not been run

doctor
  Checks the tools, the skill links and the agents, and the project if one is given
  or the current directory has a .formic folder. Exits 1 if anything required is missing.

uninstall
  Removes the links and agent files that install created. Projects are not touched.
EOF
}

# ------------------------------------------------------------------ state

load_state() {
  [ -f "$STATE_FILE" ] || return 0
  local key value
  while IFS='=' read -r key value; do
    case "$key" in
      config_dir)        [ -n "$CONFIG_DIR" ]        || CONFIG_DIR="$value" ;;
      coordinator_model) [ -n "$COORDINATOR_MODEL" ] || COORDINATOR_MODEL="$value" ;;
      sonnet_model)      [ -n "$SONNET_MODEL" ]      || SONNET_MODEL="$value" ;;
      haiku_model)       [ -n "$HAIKU_MODEL" ]       || HAIKU_MODEL="$value" ;;
    esac
  done < "$STATE_FILE"
}

save_state() {
  mkdir -p "$STATE_DIR"
  {
    printf 'config_dir=%s\n' "$CONFIG_DIR"
    printf 'coordinator_model=%s\n' "$COORDINATOR_MODEL"
    printf 'sonnet_model=%s\n' "$SONNET_MODEL"
    printf 'haiku_model=%s\n' "$HAIKU_MODEL"
    printf 'kit_dir=%s\n' "$KIT_DIR"
    printf 'kit_version=%s\n' "$KIT_VERSION"
  } > "$STATE_FILE"
}

record() {
  mkdir -p "$STATE_DIR"
  touch "$MANIFEST"
  grep -qxF "$1" "$MANIFEST" || printf '%s\n' "$1" >> "$MANIFEST"
}

# ---------------------------------------------------------------- install

link_skill() {
  local src="$1" dest="$2/$(basename "$1")"
  if [ -L "$dest" ]; then
    if [ "$(readlink "$dest")" = "$src" ]; then
      return 0
    fi
    case "$(readlink "$dest")" in
      */skills/formic-*) ;;  # an older kit location: safe to repoint
      *) if [ "$FORCE" -ne 1 ]; then warn "skipped $dest: a link to somewhere else exists (use --force)"; return 1; fi ;;
    esac
    rm "$dest"
  elif [ -e "$dest" ]; then
    if [ "$FORCE" -ne 1 ]; then warn "skipped $dest: it exists and is not a link (use --force)"; return 1; fi
    rm -rf "$dest.bak"; mv "$dest" "$dest.bak"; say "  kept the old $dest as $dest.bak"
  fi
  ln -s "$src" "$dest"
}

link_skills() {
  local target="$1" n=0 skipped=0 d
  mkdir -p "$target"
  for d in "$KIT_DIR"/skills/*/; do
    d="${d%/}"
    if link_skill "$d" "$target"; then
      n=$((n + 1)); [ "$2" = "record" ] && record "$target/$(basename "$d")"
    else
      skipped=$((skipped + 1))
    fi
  done
  say "skills: $n linked into $target"
  [ "$skipped" -eq 0 ] || warn "$skipped skills were skipped"
}

write_agent() {
  local name="$1" model="$2" flag="$3"
  local tmpl="$KIT_DIR/agents/$name.md.tmpl" dest="$CONFIG_DIR/agents/$name.md"
  if [ -e "$dest" ] && ! grep -qF "$MARKER" "$dest"; then
    if [ "$FORCE" -ne 1 ]; then
      say "agent $name: kept your existing $dest (not created by formic-kit; use --force to replace it)"
      return 0
    fi
    cp "$dest" "$dest.bak"; say "agent $name: kept the old file as $dest.bak"
  fi
  if [ -z "$model" ]; then
    if [ -e "$dest" ]; then
      say "agent $name: left as it is (no model given)"
    else
      if [ "$name" = "formic-coordinator" ]; then
        say "agent $name: not written (optional). Pass $flag <provider/model> to add it"
      else
        warn "agent $name: not written. Pass $flag <provider/model>"
        MISSING_AGENTS=1
      fi
    fi
    return 0
  fi
  case "$model" in
    */*) ;;
    *) die "$flag '$model' is not in provider/model form" ;;
  esac
  mkdir -p "$CONFIG_DIR/agents"
  # Models can contain characters that are special to sed, so substitute with awk.
  awk -v model="$model" '{ gsub(/\{\{MODEL\}\}/, model); print }' "$tmpl" > "$dest.tmp"
  mv "$dest.tmp" "$dest"
  record "$dest"
  say "agent $name: written with model $model"
}

cmd_install() {
  [ -n "$CONFIG_DIR" ] || CONFIG_DIR="$HOME/.config/opencode"
  say "formic-kit $KIT_VERSION -> $CONFIG_DIR"
  MISSING_AGENTS=0
  link_skills "$CONFIG_DIR/skills" record
  write_agent worker-haiku "$HAIKU_MODEL" --haiku-model
  write_agent worker-sonnet "$SONNET_MODEL" --sonnet-model
  write_agent formic-coordinator "$COORDINATOR_MODEL" --coordinator-model
  save_state
  say ""
  if [ "$MISSING_AGENTS" -eq 1 ]; then
    say "Some agents are missing. Rerun with the model flags above, then run: ./install.sh doctor"
    exit 1
  else
    say "Next: 'herdr integration install opencode' if it is not installed yet, then ./install.sh doctor"
    say "Then in each project: $KIT_DIR/install.sh init ."
  fi
}

# ------------------------------------------------------------------- init

cmd_init() {
  local project="${1:-.}"
  [ -d "$project" ] || die "$project is not a directory"
  project="$(cd "$project" && pwd)"
  command -v python3 >/dev/null || die "python3 is required"
  git -C "$project" rev-parse --is-inside-work-tree >/dev/null 2>&1 \
    || warn "$project is not a git repository; the coordinator needs one to run tasks"

  if [ -f "$project/.formic/board.json" ]; then
    say "board: $project/.formic/board.json already exists, left as it is"
  else
    python3 "$KIT_DIR/skills/formic-board/scripts/board.py" --root "$project" init >/dev/null
    say "board: created $project/.formic/board.json"
  fi

  if [ -f "$project/.formic/project.json" ]; then
    say "settings: $project/.formic/project.json already exists, left as it is"
  else
    cp "$KIT_DIR/templates/project.json" "$project/.formic/project.json"
    say "settings: created $project/.formic/project.json  <- fill in the check commands"
  fi

  if [ -f "$project/AGENTS.md" ] && grep -qF "$AGENTS_HEADING" "$project/AGENTS.md"; then
    say "AGENTS.md: already has the formic-kit section"
  else
    [ -f "$project/AGENTS.md" ] && printf '\n\n' >> "$project/AGENTS.md"
    cat "$KIT_DIR/templates/AGENTS-section.md" >> "$project/AGENTS.md"
    say "AGENTS.md: added the formic-kit section"
  fi

  if [ "$LOCAL_SKILLS" -eq 1 ]; then
    link_skills "$project/.opencode/skills" norecord
  fi

  say ""
  say "Next: edit .formic/project.json (typecheck, build and test commands, guideline file),"
  say "then start opencode inside herdr in $project and ask it to create or run tasks."
  say "The first opencode start in a new project takes about a minute."
}

# ----------------------------------------------------------------- doctor

FAILS=0
ok()   { printf '  ok    %s\n' "$*"; }
bad()  { printf '  FAIL  %s\n' "$*"; FAILS=$((FAILS + 1)); }
note() { printf '  note  %s\n' "$*"; }

cmd_doctor() {
  local project="${1:-}"
  [ -n "$CONFIG_DIR" ] || CONFIG_DIR="$HOME/.config/opencode"
  say "formic-kit $KIT_VERSION doctor"

  say "Tools"
  local t
  for t in opencode herdr python3 git; do
    if command -v "$t" >/dev/null; then ok "$t found"; else bad "$t is not installed or not on PATH"; fi
  done
  if command -v herdr >/dev/null; then
    local st
    st="$(herdr integration status 2>/dev/null | grep '^opencode:' || true)"
    case "$st" in
      *current*) ok "herdr opencode integration: ${st#opencode: }" ;;
      "")        bad "herdr opencode integration status unknown; run: herdr integration install opencode" ;;
      *)         bad "herdr opencode integration: ${st#opencode: }; run: herdr integration install opencode" ;;
    esac
    if [ "${HERDR_ENV:-}" = 1 ]; then ok "running inside herdr"; else note "not inside a herdr pane; the coordinator must be started inside herdr"; fi
  fi

  say "Skills"
  local total=0 linked=0 d dest
  for d in "$KIT_DIR"/skills/*/; do
    d="${d%/}"; total=$((total + 1))
    for dest in "$CONFIG_DIR/skills/$(basename "$d")" ${project:+"$project/.opencode/skills/$(basename "$d")"} ".opencode/skills/$(basename "$d")"; do
      if [ -f "$dest/SKILL.md" ]; then linked=$((linked + 1)); break; fi
    done
  done
  if [ "$linked" -eq "$total" ]; then ok "$linked of $total kit skills are reachable"
  else bad "$linked of $total kit skills are reachable; run ./install.sh (or init --local-skills)"; fi
  local broken=0 l
  if [ -d "$CONFIG_DIR/skills" ]; then
    for l in "$CONFIG_DIR"/skills/formic-*; do
      [ -L "$l" ] && [ ! -e "$l" ] && { broken=$((broken + 1)); bad "broken link $l"; }
    done
  fi
  [ "$broken" -eq 0 ] || note "broken links usually mean the kit folder moved; rerun ./install.sh"

  say "Agents"
  if command -v opencode >/dev/null; then
    local list a
    list="$(OPENCODE_CONFIG_DIR="$CONFIG_DIR" opencode agent list 2>/dev/null || true)"
    for a in worker-haiku worker-sonnet; do
      if grep -q "^$a " <<< "$list"; then
        local f="$CONFIG_DIR/agents/$a.md" m=""
        [ -f "$f" ] && m="$(awk '/^model:/ { sub(/^model: */, ""); print; exit }' "$f")"
        ok "$a${m:+ ($m)}"
        [ -f "$f" ] && ! grep -qF "$MARKER" "$f" && note "$a is your own profile, not the kit's; it sets no explicit edit and shell permissions"
      else
        bad "agent $a not found; run ./install.sh with its model flag"
      fi
    done
    if grep -q "^formic-coordinator " <<< "$list"; then ok "formic-coordinator"
    else note "formic-coordinator agent not installed (optional): pass --coordinator-model to install"; fi
  fi

  [ -n "$project" ] || { [ -d .formic ] && project="."; }
  if [ -n "$project" ]; then
    project="$(cd "$project" && pwd)"
    say "Project $project"
    if git -C "$project" rev-parse --is-inside-work-tree >/dev/null 2>&1; then ok "git repository"; else bad "not a git repository"; fi
    if [ -f "$project/.formic/board.json" ]; then
      local v
      if v="$(python3 "$KIT_DIR/skills/formic-board/scripts/board.py" --root "$project" validate 2>&1)"; then ok "board: ${v#OK: }"
      else bad "board: $(printf '%s' "$v" | head -3 | tr '\n' ' ')"; fi
    else
      bad "no .formic/board.json; run ./install.sh init $project"
    fi
    if [ -f "$project/.formic/project.json" ]; then
      local c
      c="$(python3 - "$project/.formic/project.json" <<'PY'
import json, sys
try:
    d = json.load(open(sys.argv[1]))
except Exception as e:
    print("invalid: %s" % e); sys.exit(0)
c = d.get("commands") or {}
missing = [k for k in ("typecheck", "test") if not c.get(k)]
print("missing: " + ", ".join(missing) if missing else "ok")
PY
)"
      case "$c" in
        ok)        ok "project.json has typecheck and test commands" ;;
        missing*)  note "project.json ${c}; the quality gate cannot run those checks until they are set" ;;
        *)         bad "project.json $c" ;;
      esac
    else
      bad "no .formic/project.json; run ./install.sh init $project"
    fi
    if [ -f "$project/AGENTS.md" ] && grep -qF "$AGENTS_HEADING" "$project/AGENTS.md"; then ok "AGENTS.md has the formic-kit section"
    else note "AGENTS.md has no formic-kit section; run ./install.sh init $project"; fi
  fi

  say ""
  if [ "$FAILS" -eq 0 ]; then say "All required checks passed."; else say "$FAILS required check(s) failed."; exit 1; fi
}

# -------------------------------------------------------------- uninstall

cmd_uninstall() {
  [ -f "$MANIFEST" ] || { say "nothing to remove: no install recorded in $STATE_DIR"; return 0; }
  local path n=0
  while IFS= read -r path; do
    [ -n "$path" ] || continue
    if [ -L "$path" ]; then
      rm "$path"; n=$((n + 1))
    elif [ -f "$path" ] && grep -qF "$MARKER" "$path"; then
      rm "$path"; n=$((n + 1))
    elif [ -e "$path" ]; then
      warn "left $path: it is no longer the file install created"
    fi
  done < "$MANIFEST"
  rm -f "$MANIFEST" "$STATE_FILE"
  rmdir "$STATE_DIR" 2>/dev/null || true
  say "removed $n links and agent files. Projects and their .formic folders were not touched."
}

# ------------------------------------------------------------------- main

COMMAND="install"
case "${1:-}" in
  install|init|doctor|uninstall) COMMAND="$1"; shift ;;
  -h|--help|help) usage; exit 0 ;;
esac

POSITIONAL=()
while [ $# -gt 0 ]; do
  case "$1" in
    --coordinator-model) [ $# -ge 2 ] || die "$1 needs a value"; COORDINATOR_MODEL="$2"; shift 2 ;;
    --sonnet-model)      [ $# -ge 2 ] || die "$1 needs a value"; SONNET_MODEL="$2"; shift 2 ;;
    --haiku-model)       [ $# -ge 2 ] || die "$1 needs a value"; HAIKU_MODEL="$2"; shift 2 ;;
    --config-dir)        [ $# -ge 2 ] || die "$1 needs a value"; CONFIG_DIR="$2"; shift 2 ;;
    --force)             FORCE=1; shift ;;
    --local-skills)      LOCAL_SKILLS=1; shift ;;
    -h|--help)           usage; exit 0 ;;
    -*)                  die "unknown option $1 (see --help)" ;;
    *)                   POSITIONAL+=("$1"); shift ;;
  esac
done

load_state

case "$COMMAND" in
  install)   [ ${#POSITIONAL[@]} -eq 0 ] || die "install takes no positional arguments"; cmd_install ;;
  init)      cmd_init "${POSITIONAL[0]:-.}" ;;
  doctor)    cmd_doctor "${POSITIONAL[0]:-}" ;;
  uninstall) cmd_uninstall ;;
esac
